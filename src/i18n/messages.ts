const TABLES: Record<Lang, Dict> = { en, zh, ja, ko }

export function t(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const table = TABLES[lang] ?? en
  let text = table[key] ?? en[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v))
    }
  }
  return text
}

/** Localized market disclaimer; falls back to pack English string if key missing. */
export function marketDisclaimer(lang: Lang, marketId: string, fallback: string): string {
  const key = `market.disclaimer.${marketId}`
  const table = TABLES[lang] ?? en
  return table[key] ?? en[key] ?? fallback
}
